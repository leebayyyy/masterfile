-- 3. tblauthorization_log: record supervisor overrides
CREATE TABLE IF NOT EXISTS tblauthorization_log (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  cashier_id INTEGER REFERENCES tblusers(user_id),
  supervisor_id INTEGER NOT NULL REFERENCES tblusers(user_id),
  action_type VARCHAR(100) NOT NULL,
  target_reference VARCHAR(255) DEFAULT NULL,
  shift_id INTEGER DEFAULT NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_auth_log_cashier ON tblauthorization_log(cashier_id);
CREATE INDEX IF NOT EXISTS idx_auth_log_supervisor ON tblauthorization_log(supervisor_id);
CREATE INDEX IF NOT EXISTS idx_auth_log_action ON tblauthorization_log(action_type);

-- 4. tblshifts: track cashier shifts and beginning cash
CREATE TABLE IF NOT EXISTS tblshifts (
  shift_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id INTEGER NOT NULL REFERENCES tblusers(user_id),
  terminal_id INTEGER NOT NULL REFERENCES tblpos_terminals(pos_terminal_id),
  opening_cash DECIMAL(12,2) NOT NULL DEFAULT 0.00,
  opened_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  closed_at TIMESTAMP DEFAULT NULL,
  closing_cash DECIMAL(12,2) DEFAULT NULL,
  expected_cash DECIMAL(12,2) DEFAULT NULL,
  status VARCHAR(20) NOT NULL DEFAULT 'open'
);
CREATE INDEX IF NOT EXISTS idx_shifts_user_term_status ON tblshifts(user_id, terminal_id, status);

-- 5. tbldrawer_events: track float, lift, drop, and cash sales
CREATE TABLE IF NOT EXISTS tbldrawer_events (
  event_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  shift_id INTEGER NOT NULL REFERENCES tblshifts(shift_id),
  event_type VARCHAR(50) NOT NULL, -- 'float' | 'lift' | 'drop' | 'sale'
  amount DECIMAL(12,2) NOT NULL,
  authorized_by INTEGER REFERENCES tblusers(user_id),
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_drawer_events_shift ON tbldrawer_events(shift_id);
CREATE INDEX IF NOT EXISTS idx_drawer_events_type ON tbldrawer_events(event_type);

-- 6. tblpayment_allocations: per-invoice AR FIFO allocation records
CREATE TABLE IF NOT EXISTS tblpayment_allocations (
  allocation_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  payment_id INTEGER NOT NULL REFERENCES tblpayment_header(payment_id),
  invoice_id INTEGER NOT NULL REFERENCES tblar_invoice(ar_invoice_id),
  amount_applied DECIMAL(12,2) NOT NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_payment_alloc_payment ON tblpayment_allocations(payment_id);
CREATE INDEX IF NOT EXISTS idx_payment_alloc_invoice ON tblpayment_allocations(invoice_id);
