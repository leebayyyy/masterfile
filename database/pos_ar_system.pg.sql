-- Optional trigger function for ON UPDATE CURRENT_TIMESTAMP behavior
CREATE OR REPLACE FUNCTION set_updated_at_timestamp()
RETURNS TRIGGER AS $$
BEGIN
  NEW.updated_at = CURRENT_TIMESTAMP;
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

-- --------------------------------------------------------
-- 1. tblroles
-- --------------------------------------------------------
CREATE TABLE tblroles (
  role_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  role_name VARCHAR(100) NOT NULL,
  description VARCHAR(255) DEFAULT NULL
);

-- --------------------------------------------------------
-- 2. tblunit_of_measure
-- --------------------------------------------------------
CREATE TABLE tblunit_of_measure (
  unit_of_measure_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  measure_name VARCHAR(100) NOT NULL UNIQUE,
  description VARCHAR(255) DEFAULT NULL
);

-- --------------------------------------------------------
-- 3. tblproduct_categories
-- --------------------------------------------------------
CREATE TABLE tblproduct_categories (
  category_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  category_name VARCHAR(150) NOT NULL,
  description VARCHAR(255) DEFAULT NULL
);

-- --------------------------------------------------------
-- 4. tblpos_terminals
-- --------------------------------------------------------
CREATE TABLE tblpos_terminals (
  pos_terminal_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  terminal_name VARCHAR(150) NOT NULL
);

-- --------------------------------------------------------
-- 5. tblpayment_method
-- --------------------------------------------------------
CREATE TABLE tblpayment_method (
  payment_method_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  method_name VARCHAR(100) NOT NULL,
  description VARCHAR(255) DEFAULT NULL,
  is_active SMALLINT DEFAULT 1
);

-- --------------------------------------------------------
-- 6. tblpromo
-- --------------------------------------------------------
CREATE TABLE tblpromo (
  promo_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  promo_name VARCHAR(150) NOT NULL,
  description VARCHAR(255) DEFAULT NULL,
  start_date DATE DEFAULT NULL,
  end_date DATE DEFAULT NULL,
  discount_rate DECIMAL(10,2) DEFAULT NULL,
  is_active SMALLINT DEFAULT 1
);

-- --------------------------------------------------------
-- 7. tblar_customer_types
-- --------------------------------------------------------
CREATE TABLE tblar_customer_types (
  customer_type_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  type_name VARCHAR(100) NOT NULL,
  description VARCHAR(255) DEFAULT NULL,
  days INTEGER DEFAULT NULL
);

-- --------------------------------------------------------
-- 8. tblusers
-- --------------------------------------------------------
CREATE TABLE tblusers (
  user_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  username VARCHAR(100) NOT NULL UNIQUE,
  first_name VARCHAR(100) NOT NULL,
  last_name VARCHAR(100) NOT NULL,
  role_id INTEGER NOT NULL REFERENCES tblroles(role_id),
  role VARCHAR(50) DEFAULT 'cashier',
  email VARCHAR(150) DEFAULT NULL,
  phone VARCHAR(30) DEFAULT NULL,
  password_hash VARCHAR(255) DEFAULT NULL,
  is_active SMALLINT DEFAULT 1
);
CREATE INDEX idx_users_role ON tblusers(role_id);
CREATE UNIQUE INDEX idx_users_username_lower ON tblusers(LOWER(username));

-- --------------------------------------------------------
-- 9. tblar_customers
-- --------------------------------------------------------
CREATE TABLE tblar_customers (
  ar_customer_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  customer_name VARCHAR(200) NOT NULL,
  customer_type_id INTEGER NOT NULL REFERENCES tblar_customer_types(customer_type_id),
  contact_name VARCHAR(150) DEFAULT NULL,
  contact_phone VARCHAR(30) DEFAULT NULL,
  billing_address VARCHAR(255) DEFAULT NULL,
  email VARCHAR(150) DEFAULT NULL,
  credit_limit DECIMAL(12,2) NOT NULL DEFAULT 0.00,
  is_active SMALLINT DEFAULT 1
);
CREATE INDEX idx_ar_customer_type ON tblar_customers(customer_type_id);

-- --------------------------------------------------------
-- 10. tblsku_card
-- --------------------------------------------------------
CREATE TABLE tblsku_card (
  sku_card_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ar_customer_id INTEGER NOT NULL REFERENCES tblar_customers(ar_customer_id),
  card_number VARCHAR(100) DEFAULT NULL,
  issued_date DATE DEFAULT NULL,
  expiry_date DATE DEFAULT NULL,
  points_balance DECIMAL(10,2) DEFAULT NULL,
  is_active SMALLINT DEFAULT 1
);
CREATE INDEX idx_suki_customer ON tblsku_card(ar_customer_id);

-- --------------------------------------------------------
-- 11. tblproducts
-- --------------------------------------------------------
CREATE TABLE tblproducts (
  product_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  barcode VARCHAR(100) DEFAULT NULL,
  price DECIMAL(10,2) DEFAULT NULL,
  product_name VARCHAR(200) NOT NULL,
  category_id INTEGER NOT NULL REFERENCES tblproduct_categories(category_id),
  unit_of_measure_id INTEGER NOT NULL REFERENCES tblunit_of_measure(unit_of_measure_id),
  price_tier VARCHAR(100) DEFAULT NULL,
  wholesale_price DECIMAL(10,2) DEFAULT NULL,
  is_active SMALLINT DEFAULT 1
);
CREATE UNIQUE INDEX idx_products_barcode ON tblproducts(barcode);
CREATE INDEX idx_products_category ON tblproducts(category_id);
CREATE INDEX idx_products_unit_id ON tblproducts(unit_of_measure_id);

-- --------------------------------------------------------
-- 12. tblproduct_promo
-- --------------------------------------------------------
CREATE TABLE tblproduct_promo (
  product_promo_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  product_id INTEGER NOT NULL REFERENCES tblproducts(product_id),
  promo_id INTEGER NOT NULL REFERENCES tblpromo(promo_id)
);
CREATE INDEX idx_product_promo_product ON tblproduct_promo(product_id);
CREATE INDEX idx_product_promo_promo ON tblproduct_promo(promo_id);

-- --------------------------------------------------------
-- 13. tblwholesale_prices
-- --------------------------------------------------------
CREATE TABLE tblwholesale_prices (
  wholesale_price_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  product_id INTEGER NOT NULL REFERENCES tblproducts(product_id),
  wholesale_price DECIMAL(10,2) DEFAULT NULL,
  price_tier VARCHAR(100) DEFAULT NULL,
  effective_from DATE DEFAULT NULL,
  effective_to DATE DEFAULT NULL
);
CREATE INDEX idx_wholesale_prices_product ON tblwholesale_prices(product_id);

-- --------------------------------------------------------
-- 14. tblheld_transactions
-- --------------------------------------------------------
CREATE TABLE tblheld_transactions (
  held_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  hold_reference VARCHAR(100) NOT NULL,
  cashier_user_id INTEGER NOT NULL REFERENCES tblusers(user_id),
  customer_label VARCHAR(255) DEFAULT NULL,
  sale_type VARCHAR(50) DEFAULT 'Cash',
  items_json TEXT NOT NULL,
  cart_state_json TEXT DEFAULT NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX idx_held_cashier ON tblheld_transactions(cashier_user_id);
CREATE INDEX idx_held_created_at ON tblheld_transactions(created_at);

CREATE OR REPLACE VIEW held_transactions AS
  SELECT * FROM tblheld_transactions;

-- --------------------------------------------------------
-- 15. tblsales
-- --------------------------------------------------------
CREATE TABLE tblsales (
  sale_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  pos_terminal_id INTEGER NOT NULL REFERENCES tblpos_terminals(pos_terminal_id),
  cashier_user_id INTEGER NOT NULL REFERENCES tblusers(user_id),
  sale_date DATE NOT NULL,
  sale_type VARCHAR(100) DEFAULT NULL,
  payment_method_id INTEGER DEFAULT NULL REFERENCES tblpayment_method(payment_method_id),
  ar_customer_id INTEGER DEFAULT NULL REFERENCES tblar_customers(ar_customer_id),
  price DECIMAL(10,2) DEFAULT NULL,
  tax_total DECIMAL(10,2) DEFAULT NULL,
  total_amount DECIMAL(10,2) DEFAULT NULL,
  balance DECIMAL(10,2) DEFAULT NULL,
  suki_card_id INTEGER DEFAULT NULL REFERENCES tblsku_card(sku_card_id),
  suki_card_status VARCHAR(10) DEFAULT NULL,
  suki_points_balance DECIMAL(10,2) DEFAULT NULL
);
CREATE INDEX idx_sales_terminal ON tblsales(pos_terminal_id);
CREATE INDEX idx_sales_cashier ON tblsales(cashier_user_id);
CREATE INDEX idx_sales_suki_card ON tblsales(suki_card_id);
CREATE INDEX idx_sales_ar_customer ON tblsales(ar_customer_id);
CREATE INDEX idx_sales_payment_method ON tblsales(payment_method_id);

-- --------------------------------------------------------
-- 16. tblsales_detail
-- --------------------------------------------------------
CREATE TABLE tblsales_detail (
  sales_detail_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  sale_id INTEGER NOT NULL REFERENCES tblsales(sale_id),
  product_id INTEGER NOT NULL REFERENCES tblproducts(product_id),
  promo_id INTEGER DEFAULT NULL REFERENCES tblpromo(promo_id),
  quantity DECIMAL(10,2) DEFAULT NULL,
  unit_price DECIMAL(10,2) DEFAULT NULL,
  discount DECIMAL(10,2) DEFAULT NULL,
  promo_discount DECIMAL(10,2) NOT NULL DEFAULT 0.00,
  line_total DECIMAL(10,2) DEFAULT NULL,
  cost_at_sale DECIMAL(10,2) DEFAULT NULL
);
CREATE INDEX idx_sales_detail_sale ON tblsales_detail(sale_id);
CREATE INDEX idx_sales_detail_product ON tblsales_detail(product_id);
CREATE INDEX idx_sales_detail_promo ON tblsales_detail(promo_id);

-- --------------------------------------------------------
-- 17. tblar_invoice
-- --------------------------------------------------------
CREATE TABLE tblar_invoice (
  ar_invoice_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  invoice_number VARCHAR(100) DEFAULT NULL,
  ar_customer_id INTEGER NOT NULL REFERENCES tblar_customers(ar_customer_id),
  sale_id INTEGER NOT NULL UNIQUE REFERENCES tblsales(sale_id),
  created_by_user_id INTEGER NOT NULL REFERENCES tblusers(user_id),
  invoice_date DATE DEFAULT NULL,
  due_date DATE DEFAULT NULL,
  invoice_amount DECIMAL(10,2) DEFAULT NULL,
  balance DECIMAL(10,2) DEFAULT NULL,
  status VARCHAR(50) DEFAULT NULL
);
CREATE INDEX idx_invoice_customer ON tblar_invoice(ar_customer_id);
CREATE INDEX idx_invoice_user ON tblar_invoice(created_by_user_id);

-- --------------------------------------------------------
-- 18. tblar_credit_memo
-- --------------------------------------------------------
