  credit_memo_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ar_invoice_id INTEGER NOT NULL REFERENCES tblar_invoice(ar_invoice_id),
  issue_date DATE DEFAULT NULL,
  amount DECIMAL(10,2) DEFAULT NULL,
  invoice_balance DECIMAL(10,2) DEFAULT NULL,
  issued_by_user_id INTEGER NOT NULL REFERENCES tblusers(user_id),
  status VARCHAR(50) DEFAULT NULL
);
CREATE INDEX idx_credit_invoice ON tblar_credit_memo(ar_invoice_id);
CREATE INDEX idx_credit_user ON tblar_credit_memo(issued_by_user_id);

-- --------------------------------------------------------
-- 19. tblar_debit_memo
-- --------------------------------------------------------
CREATE TABLE tblar_debit_memo (
  debit_memo_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ar_invoice_id INTEGER NOT NULL REFERENCES tblar_invoice(ar_invoice_id),
  issue_date DATE DEFAULT NULL,
  amount DECIMAL(10,2) DEFAULT NULL,
  issued_by_user_id INTEGER NOT NULL REFERENCES tblusers(user_id),
  status VARCHAR(50) DEFAULT NULL
);
CREATE INDEX idx_debit_invoice ON tblar_debit_memo(ar_invoice_id);
CREATE INDEX idx_debit_user ON tblar_debit_memo(issued_by_user_id);

-- --------------------------------------------------------
-- 20. tblpayment_header
-- --------------------------------------------------------
CREATE TABLE tblpayment_header (
  payment_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  payment_date DATE DEFAULT NULL,
  amount DECIMAL(10,2) DEFAULT NULL,
  payment_method_id INTEGER NOT NULL REFERENCES tblpayment_method(payment_method_id),
  processed_by_user_id INTEGER NOT NULL REFERENCES tblusers(user_id),
  reference_number VARCHAR(100) DEFAULT NULL,
  notes VARCHAR(255) DEFAULT NULL
);
CREATE INDEX idx_payment_method ON tblpayment_header(payment_method_id);
CREATE INDEX idx_payment_user ON tblpayment_header(processed_by_user_id);

-- --------------------------------------------------------
-- 21. tblpayment_detail
-- --------------------------------------------------------
CREATE TABLE tblpayment_detail (
  payment_detail_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  payment_id INTEGER NOT NULL REFERENCES tblpayment_header(payment_id),
  ar_invoice_id INTEGER NOT NULL REFERENCES tblar_invoice(ar_invoice_id),
  applied_amount DECIMAL(10,2) DEFAULT NULL,
  applied_date DATE DEFAULT NULL
);
CREATE INDEX idx_payment_detail_payment ON tblpayment_detail(payment_id);
CREATE INDEX idx_payment_detail_invoice ON tblpayment_detail(ar_invoice_id);

-- --------------------------------------------------------
-- 22. tblauthorization_log
-- --------------------------------------------------------
CREATE TABLE tblauthorization_log (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  cashier_id INTEGER REFERENCES tblusers(user_id),
  supervisor_id INTEGER NOT NULL REFERENCES tblusers(user_id),
  action_type VARCHAR(100) NOT NULL,
  target_reference VARCHAR(255) DEFAULT NULL,
  shift_id INTEGER DEFAULT NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX idx_auth_log_cashier ON tblauthorization_log(cashier_id);
CREATE INDEX idx_auth_log_supervisor ON tblauthorization_log(supervisor_id);
CREATE INDEX idx_auth_log_action ON tblauthorization_log(action_type);

-- --------------------------------------------------------
-- 23. tblshifts
-- --------------------------------------------------------
CREATE TABLE tblshifts (
  shift_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id INTEGER NOT NULL REFERENCES tblusers(user_id),
  terminal_id INTEGER NOT NULL REFERENCES tblpos_terminals(pos_terminal_id),
  opening_cash DECIMAL(12,2) NOT NULL DEFAULT 0.00,
  opened_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  closed_at TIMESTAMP DEFAULT NULL,
  closing_cash DECIMAL(12,2) DEFAULT NULL,
  expected_cash DECIMAL(12,2) DEFAULT NULL,
  status VARCHAR(20) NOT NULL DEFAULT 'open'
);
CREATE INDEX idx_shifts_user_term_status ON tblshifts(user_id, terminal_id, status);

-- --------------------------------------------------------
-- 24. tbldrawer_events
-- --------------------------------------------------------
CREATE TABLE tbldrawer_events (
  event_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  shift_id INTEGER NOT NULL REFERENCES tblshifts(shift_id),
  event_type VARCHAR(50) NOT NULL,
  amount DECIMAL(12,2) NOT NULL,
  authorized_by INTEGER REFERENCES tblusers(user_id),
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX idx_drawer_events_shift ON tbldrawer_events(shift_id);
CREATE INDEX idx_drawer_events_type ON tbldrawer_events(event_type);

-- --------------------------------------------------------
-- 25. tblpayment_allocations
-- --------------------------------------------------------
CREATE TABLE tblpayment_allocations (
  allocation_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  payment_id INTEGER NOT NULL REFERENCES tblpayment_header(payment_id),
  invoice_id INTEGER NOT NULL REFERENCES tblar_invoice(ar_invoice_id),
  amount_applied DECIMAL(12,2) NOT NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX idx_payment_alloc_payment ON tblpayment_allocations(payment_id);
CREATE INDEX idx_payment_alloc_invoice ON tblpayment_allocations(invoice_id);

